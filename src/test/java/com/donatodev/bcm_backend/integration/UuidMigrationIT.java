package com.donatodev.bcm_backend.integration;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Pattern;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.FlywayException;
import org.flywaydb.core.api.MigrationVersion;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.testcontainers.mysql.MySQLContainer;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * V55 (ADR-0009) on real MySQL: a V54 database with every kind of reference is
 * migrated to UUIDs, and nothing about its relationships may change.
 *
 * V55 is generated by {@code scripts/uuid-migration/generate_v55.py}; this test
 * applies it (and what follows it) with Flyway directly, without a Spring
 * context, so it can stop at V54 first and seed data the old way.
 */
@Tag("integration")
class UuidMigrationIT {

    /** Where fingerprint.sql lives (V55 itself is a normal migration on the classpath). */
    private static final String MIGRATION_DIR = "scripts/uuid-migration";
    private static final Pattern UUID_V4 = Pattern.compile(
            "^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$");

    // Same server collation as production and the other MySQL ITs: the database
    // default differing from some tables' collation is exactly what V55 must survive.
    private static final MySQLContainer MYSQL = new MySQLContainer("mysql:8.0")
            .withDatabaseName("bcm_uuid")
            .withUsername("bcm_it")
            .withPassword("bcm_it_password")
            .withCommand("--character-set-server=utf8mb4", "--collation-server=utf8mb4_unicode_ci");

    static {
        MYSQL.start();
    }

    @Test
    void everyRelationshipSurvivesTheMigration() throws Exception {
        String db = freshDatabase("v55_full");
        migrate(db, "54");
        runScript(db, Path.of("src/test/resources/uuid-migration/v54-graph.sql"));
        List<String> before = fingerprint(db);
        List<String> schemaBefore = keysAndIndexes(db);
        Map<String, Long> oldOrgIds = slugToLongId(db);

        migrate(db, null);

        List<String> expected = new ArrayList<>(before);
        String notifications = expected.stream().filter(l -> l.startsWith("count\tnotifications\t")).findFirst().orElseThrow();
        long count = Long.parseLong(notifications.split("\t")[2]);
        // The one row violating notifications.user_id (ON DELETE CASCADE) is removed, as the key prescribes.
        expected.set(expected.indexOf(notifications), "count\tnotifications\t" + (count - 1));
        assertThat(fingerprint(db)).containsExactlyElementsOf(expected);
        assertThat(keysAndIndexes(db)).containsExactlyElementsOf(schemaBefore);

        try (Connection c = connect(db); Statement s = c.createStatement()) {
            assertThat(single(s, "SELECT COUNT(*) FROM information_schema.columns WHERE table_schema = DATABASE() "
                    + "AND data_type IN ('bigint', 'int') AND (column_name = 'id' OR column_name LIKE '%\\_id' "
                    + "OR column_name IN ('modified_by', 'submitted_by')) AND table_name <> 'flyway_schema_history' "
                    + "AND NOT (table_name = 'organizations' AND column_name = 'legacy_id')"))
                    .as("integer id columns left").isEqualTo("0");
            for (String[] column : rows(s, "SELECT table_name, column_name FROM information_schema.columns "
                    + "WHERE table_schema = DATABASE() AND data_type = 'char' AND character_maximum_length = 36")) {
                for (String[] value : rows(s, "SELECT `" + column[1] + "` FROM `" + column[0] + "` WHERE `" + column[1] + "` IS NOT NULL")) {
                    assertThat(value[0]).as(column[0] + "." + column[1]).matches(UUID_V4);
                }
            }
            for (String[] org : rows(s, "SELECT slug, legacy_id FROM organizations")) {
                assertThat(Long.valueOf(org[1])).as("legacy id of " + org[0]).isEqualTo(oldOrgIds.get(org[0]));
            }
            // SET NULL violation cleared, CASCADE one deleted, id-bearing caches emptied, maps gone.
            assertThat(single(s, "SELECT default_manager_id IS NULL FROM contract_templates WHERE name = 'Vuoto'")).isEqualTo("1");
            assertThat(single(s, "SELECT COUNT(*) FROM notifications WHERE title = 'Orfana'")).isEqualTo("0");
            assertThat(single(s, "SELECT COUNT(*) FROM refresh_tokens")).isEqualTo("0");
            assertThat(single(s, "SELECT COUNT(*) FROM ml_result_cache")).isEqualTo("0");
            assertThat(single(s, "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE() "
                    + "AND table_name LIKE 'uuid\\_%'")).isEqualTo("0");
            assertThat(Integer.parseInt(single(s, "SELECT MAX(CAST(version AS UNSIGNED)) FROM flyway_schema_history WHERE success = 1"))).isGreaterThanOrEqualTo(55);
        }
    }

    @Test
    void aViolationOfAKeyWithoutCascadeStopsBeforeAnythingChanges() throws Exception {
        String db = freshDatabase("v55_guard");
        migrate(db, "54");
        runScript(db, Path.of("src/test/resources/uuid-migration/v54-graph.sql"));
        try (Connection c = connect(db); Statement s = c.createStatement()) {
            s.execute("SET FOREIGN_KEY_CHECKS = 0");
            s.execute("UPDATE contracts SET counterparty_id = 149999 WHERE contract_number = 'ALF-2'");
            s.execute("SET FOREIGN_KEY_CHECKS = 1");
        }
        List<String> before = fingerprint(db);

        assertThatThrownBy(() -> migrate(db, null)).isInstanceOf(FlywayException.class)
                .hasStackTraceContaining("contracts__counterparty_id__has_orphans");

        assertThat(fingerprint(db)).as("data untouched").containsExactlyElementsOf(before);
        try (Connection c = connect(db); Statement s = c.createStatement()) {
            assertThat(single(s, "SELECT data_type FROM information_schema.columns WHERE table_schema = DATABASE() "
                    + "AND table_name = 'contracts' AND column_name = 'id'")).isEqualTo("bigint");
        }
    }

    // ── helpers ─────────────────────────────────────────────────────────────

    private static String freshDatabase(String name) throws SQLException {
        try (Connection c = DriverManager.getConnection(MYSQL.getJdbcUrl(), "root", MYSQL.getPassword());
             Statement s = c.createStatement()) {
            s.execute("DROP DATABASE IF EXISTS " + name);
            s.execute("CREATE DATABASE " + name + " CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        }
        return name;
    }

    private static String url(String db) {
        return MYSQL.getJdbcUrl().replace("/bcm_uuid", "/" + db) + (MYSQL.getJdbcUrl().contains("?") ? "&" : "?")
                + "allowMultiQueries=false";
    }

    private static Connection connect(String db) throws SQLException {
        return DriverManager.getConnection(url(db), "root", MYSQL.getPassword());
    }

    /** Migrates to {@code target} (null = latest). */
    private static void migrate(String db, String target) {
        var config = Flyway.configure().dataSource(url(db), "root", MYSQL.getPassword()).locations("classpath:db/migration");
        if (target != null) {
            config.target(MigrationVersion.fromVersion(target));
        }
        config.load().migrate();
    }

    private static void runScript(String db, Path script) throws IOException, SQLException {
        try (Connection c = connect(db); Statement s = c.createStatement()) {
            for (String statement : statements(script)) {
                s.execute(statement);
            }
        }
    }

    /** Statements of a file: comments dropped, split at semicolons that end a line. */
    private static List<String> statements(Path file) throws IOException {
        StringBuilder sql = new StringBuilder();
        for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
            if (!line.stripLeading().startsWith("--")) {
                sql.append(line).append('\n');
            }
        }
        List<String> result = new ArrayList<>();
        for (String part : sql.toString().split(";\\s*\\n")) {
            if (!part.isBlank()) {
                result.add(part.strip());
            }
        }
        return result;
    }

    private static List<String> fingerprint(String db) throws IOException, SQLException {
        List<String> lines = new ArrayList<>();
        try (Connection c = connect(db); Statement s = c.createStatement()) {
            for (String statement : statements(Path.of(MIGRATION_DIR, "fingerprint.sql"))) {
                if (!s.execute(statement)) {
                    continue;
                }
                try (ResultSet rs = s.getResultSet()) {
                    int columns = rs.getMetaData().getColumnCount();
                    while (rs.next()) {
                        List<String> values = new ArrayList<>();
                        for (int i = 1; i <= columns; i++) {
                            values.add(String.valueOf(rs.getString(i)));
                        }
                        lines.add(String.join("\t", values));
                    }
                }
            }
        }
        return lines;
    }

    private static List<String> keysAndIndexes(String db) throws SQLException {
        List<String> lines = new ArrayList<>();
        try (Connection c = connect(db); Statement s = c.createStatement()) {
            for (String[] row : rows(s, "SELECT k.table_name, k.constraint_name, k.column_name, k.referenced_table_name, "
                    + "r.delete_rule, r.update_rule FROM information_schema.key_column_usage k "
                    + "JOIN information_schema.referential_constraints r ON r.constraint_schema = k.table_schema "
                    + "AND r.constraint_name = k.constraint_name WHERE k.table_schema = DATABASE() ORDER BY 1, 2")) {
                lines.add("FK " + String.join(" ", row));
            }
            for (String[] row : rows(s, "SELECT table_name, index_name, non_unique, GROUP_CONCAT(column_name ORDER BY seq_in_index) "
                    + "FROM information_schema.statistics WHERE table_schema = DATABASE() AND table_name <> 'flyway_schema_history' "
                    + "GROUP BY table_name, index_name, non_unique ORDER BY 1, 2")) {
                lines.add("IDX " + String.join(" ", row));
            }
        }
        return lines;
    }

    private static Map<String, Long> slugToLongId(String db) throws SQLException {
        Map<String, Long> ids = new HashMap<>();
        try (Connection c = connect(db); Statement s = c.createStatement()) {
            for (String[] row : rows(s, "SELECT slug, id FROM organizations")) {
                ids.put(row[0], Long.valueOf(row[1]));
            }
        }
        return ids;
    }

    private static List<String[]> rows(Statement s, String sql) throws SQLException {
        List<String[]> result = new ArrayList<>();
        try (ResultSet rs = s.executeQuery(sql)) {
            int columns = rs.getMetaData().getColumnCount();
            while (rs.next()) {
                String[] row = new String[columns];
                for (int i = 1; i <= columns; i++) {
                    row[i - 1] = rs.getString(i);
                }
                result.add(row);
            }
        }
        return result;
    }

    private static String single(Statement s, String sql) throws SQLException {
        return rows(s, sql).getFirst()[0];
    }
}
